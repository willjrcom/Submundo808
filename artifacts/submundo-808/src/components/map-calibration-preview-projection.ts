/** North-up metric projection of the saved GPS quadrilateral for the calibration preview.
 * x increases eastward, y increases southward. Never change the user's saved corner order.
 * This is an overhead geographical reference, not a 3D rendering or satellite-image overlay.
 */
export type GeoPosition={lat:number;lng:number};
export type CalibrationQuad={tl:GeoPosition;tr:GeoPosition;br:GeoPosition;bl:GeoPosition};
export type PreviewPoint={x:number;y:number};
const M_PER_DEGREE=111320;
const CORNERS=['tl','tr','br','bl'] as const;
const compact=(value:number)=>Number(value.toFixed(3));
export function calibrationPreviewProjection(
 frame:CalibrationQuad,{width=420,height=304,padding=36}:{width?:number;height?:number;padding?:number}={}
){
 const middleLat=CORNERS.reduce((n,key)=>n+frame[key].lat,0)/4;
 const middleLng=CORNERS.reduce((n,key)=>n+frame[key].lng,0)/4;
 const metersX=M_PER_DEGREE*Math.cos(middleLat*Math.PI/180);
 const xy=(p:GeoPosition)=>({x:(p.lng-middleLng)*metersX,y:(middleLat-p.lat)*M_PER_DEGREE});
 const points=CORNERS.map(key=>xy(frame[key]));
 const minX=Math.min(...points.map(p=>p.x)),maxX=Math.max(...points.map(p=>p.x));
 const minY=Math.min(...points.map(p=>p.y)),maxY=Math.max(...points.map(p=>p.y));
 const spanX=maxX-minX,spanY=maxY-minY;
 if(spanX<=1||spanY<=1||width<=padding*2||height<=padding*2)throw Error('Limites de calibração inválidos para a visualização.');
 const scale=Math.min((width-2*padding)/spanX,(height-2*padding)/spanY);
 const offsetX=(width-spanX*scale)/2,offsetY=(height-spanY*scale)/2;
 const projectGps=(p:GeoPosition):PreviewPoint=>{
  const metric=xy(p);
  return {x:offsetX+(metric.x-minX)*scale,y:offsetY+(maxY-metric.y)*scale};
 };
 const corners=Object.fromEntries(CORNERS.map(key=>[key,projectGps(frame[key])])) as Record<typeof CORNERS[number],PreviewPoint>;
 const pointAt=(x:number,y:number):PreviewPoint=>{
  const u=x/100,v=y/100;
  const mix=(axis:'x'|'y')=>corners.tl[axis]*(1-u)*(1-v)+corners.tr[axis]*u*(1-v)+
    corners.bl[axis]*(1-u)*v+corners.br[axis]*u*v;
  return {x:mix('x'),y:mix('y')};
 };
 return {corners,pointAt,projectGps};
}
export const coordinateString=(point:PreviewPoint)=>compact(point.x)+' '+compact(point.y);
const lineTo=(p:PreviewPoint)=>'L'+coordinateString(p);
const moveTo=(p:PreviewPoint)=>'M'+coordinateString(p);
type Mapping=(x:number,y:number)=>PreviewPoint;
/** Map the actual editor silhouette (M/L/Q/C/Z) through the calibrated quadrilateral.
 * Beziers are sampled because bilinear GPS warping is not an affine SVG transform.
 * Ellipse arcs generated by areaPath() are sampled separately with ellipse bounds.
 */
export function projectEditorAreaPath(
 path:string,pointAt:Mapping,ellipse?:{x:number;y:number;width:number;height:number}
):string{
 if(!path.trim())return '';
 if(/\bA\s*[-+0-9.]/.test(path)||/\sA/.test(path)){
  if(!ellipse)return '';
  const pts=Array.from({length:72},(_,i)=>{
   const t=2*Math.PI*i/72;
   return pointAt(ellipse.x+ellipse.width*(1+Math.cos(t))/2,
                  ellipse.y+ellipse.height*(1+Math.sin(t))/2);
  });
  return moveTo(pts[0])+pts.slice(1).map(lineTo).join('')+'Z';
 }
 const tokens=path.match(/[MLQCZ]|[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?/g)||[];
 let i=0,out='',command='',current={x:0,y:0},first={x:0,y:0};
 const num=()=>Number(tokens[i++]);
 const emitPoint=(p:PreviewPoint,isStart=false)=>{out+=(isStart?'M':'L')+coordinateString(pointAt(p.x,p.y));};
 while(i<tokens.length){
  if(/^[MLQCZ]$/.test(tokens[i]))command=tokens[i++];
  if(command==='M'){
   const x=num(),y=num();if(!Number.isFinite(x+y))return '';
   current={x,y};first={x,y};emitPoint(current,true);command='L';
  }else if(command==='L'){
   const x=num(),y=num();if(!Number.isFinite(x+y))return '';
   current={x,y};emitPoint(current);
  }else if(command==='Q'){
   const control={x:num(),y:num()},end={x:num(),y:num()},from=current;
   if(!Number.isFinite(control.x+control.y+end.x+end.y))return '';
   for(let step=1;step<=14;step++){
    const t=step/14,s=1-t;
    emitPoint({x:s*s*from.x+2*s*t*control.x+t*t*end.x,
               y:s*s*from.y+2*s*t*control.y+t*t*end.y});
   }
   current=end;
  }else if(command==='C'){
   const c1={x:num(),y:num()},c2={x:num(),y:num()},end={x:num(),y:num()},from=current;
   if(!Number.isFinite(c1.x+c1.y+c2.x+c2.y+end.x+end.y))return '';
   for(let step=1;step<=20;step++){
    const t=step/20,s=1-t;
    emitPoint({x:s*s*s*from.x+3*s*s*t*c1.x+3*s*t*t*c2.x+t*t*t*end.x,
               y:s*s*s*from.y+3*s*s*t*c1.y+3*s*t*t*c2.y+t*t*t*end.y});
   }
   current=end;
  }else if(command==='Z'){
   out+='Z';current=first;command='';
  }else{return '';}
 }
 return out;
}
